constexpr int kIconPixels = 32;
constexpr int kIconMaxPixels = 48;   // BIGGERSIZEOK can hand back 96 or 256
constexpr int kIconCacheCap = 512;   // ~2 KB each; a full list still fits
constexpr int kUsageCap = 200;       // launch history kept, most recent first

// Enumerating AppsFolder measures ~300 ms warm and ~600 ms cold, and that is
// the shell's own cost - asking for no display names at all is just as slow.
// It must therefore never land on a summon, so the window is far longer than
// any burst of launcher use; installing an app is the rare event, and the
// plugin triggers a scan shortly after startup anyway.
constexpr int kRescanWindowMs = 5 * 60 * 1000;

// AppsFolder hands out a bare app id, which on its own parses back to
// nothing (0x80070002). This is the prefix that makes it an absolute name
// SHParseDisplayName and SHCreateItemFromParsingName both accept.
const QString kAppsFolderPrefix = QStringLiteral("shell:AppsFolder\\");

// Start-menu shortcuts with no registered AppUserModelID get a synthesised
// one. It is a GUID with a fixed prefix: nothing to show the user, and
// matching against it would only invent hits on its hex digits.
bool isSynthesisedAppId(const QString &appId)
{
    return appId.startsWith(QStringLiteral("Microsoft.AutoGenerated."));
}

// "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App" -> "Microsoft.WindowsCalculator".
// Both what is shown and what is matched against: the family hash is random
// letters, and the "!App" entry point is shared by nearly every packaged app,
// so keeping either only manufactures matches.
QString prettyAppId(const QString &appId)
{
    if (isSynthesisedAppId(appId))
        return {};
    if (!appId.contains(QLatin1Char('!')))
        return appId; // a Win32 entry: usually just "chrome.exe"
    const qsizetype underscore = appId.indexOf(QLatin1Char('_'));
    return underscore > 0 ? appId.left(underscore) : appId;
}

// The shell hands out a 32-bit top-down DIB. Converted by hand rather than
// through QImage::fromHBITMAP because the alpha channel is the whole point
// here - an icon that loses it renders as a black tile - and this spells the
// format out instead of depending on what the helper picks.
QImage imageFromHBitmap(HBITMAP bitmap)
{
    BITMAP header = {};
    if (!GetObjectW(bitmap, sizeof(header), &header)
        || header.bmWidth <= 0 || header.bmHeight <= 0) {
        return {};
    }

    QImage image(header.bmWidth, header.bmHeight, QImage::Format_ARGB32_Premultiplied);
    if (image.isNull())
        return {};

    BITMAPINFO info = {};
    info.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    info.bmiHeader.biWidth = header.bmWidth;
    info.bmiHeader.biHeight = -header.bmHeight; // negative: top-down, as QImage stores it
    info.bmiHeader.biPlanes = 1;
    info.bmiHeader.biBitCount = 32;
    info.bmiHeader.biCompression = BI_RGB;

    const HDC dc = GetDC(nullptr);
    const int rows = GetDIBits(dc, bitmap, 0, UINT(header.bmHeight),
                               image.bits(), &info, DIB_RGB_COLORS);
    ReleaseDC(nullptr, dc);
    if (rows == 0)
        return {};

    // A few icon sources come back 32bpp with the alpha byte left at zero,
    // which is indistinguishable from fully transparent. Nothing is lost by
    // forcing those opaque: a genuinely invisible icon is not a case worth
    // preserving.
    const int pixels = image.width() * image.height();
    auto *bits = reinterpret_cast<quint32 *>(image.bits());
    bool anyAlpha = false;
    for (int i = 0; i < pixels; ++i) {
        if ((bits[i] & 0xFF000000u) != 0) {
            anyAlpha = true;
            break;
        }
    }
    if (!anyAlpha) {
        for (int i = 0; i < pixels; ++i)
            bits[i] |= 0xFF000000u;
    }
    return image;
}

// "Visual Studio Code" -> "vsc". Its own matching tier, so "vsc" finds it
// without that run of letters appearing in the name anywhere.
QString initialsOf(const QString &name)
{
    QString out;
    bool atWordStart = true;
    for (const QChar c : name) {
        if (!c.isLetterOrNumber()) {
            atWordStart = true;
            continue;
        }
        if (atWordStart)
            out.append(c.toLower());
        atWordStart = false;
    }
    return out;
}

// fzf-lite, anchored: the query's first character has to land on a word
// start, and the rest must then appear in order. Adjacent hits are free, each
// gap costs, so "vsc" scores better against "Visual Studio Code" than against
// "Verbose Syslog Console". Returns a penalty, or -1 for no match.
//
// The anchor is what stops this last-resort tier from being a junk drawer.
// Unanchored, "pppp" is a subsequence of "Sample Desktop Apps" - and of most
// long names - so a query of pure noise still filled the list with confident
// looking matches.
int subsequencePenalty(const QString &hay, const QString &needle)
{
    if (hay.isEmpty() || needle.isEmpty())
        return -1;

    qsizetype start = -1;
    for (qsizetype i = 0; i < hay.size(); ++i) {
        if (hay.at(i) == needle.at(0) && (i == 0 || !hay.at(i - 1).isLetterOrNumber())) {
            start = i;
            break;
        }
    }
    if (start < 0)
        return -1;

    qsizetype at = start;
    qsizetype previous = -2;
    int penalty = int(std::min<qsizetype>(40, start)); // a later anchor matches less well
    for (const QChar c : needle) {
        while (at < hay.size() && hay.at(at) != c)
            ++at;
        if (at >= hay.size())
            return -1;
        if (at != previous + 1) {                     // a gap, not a run
            // Steep on purpose: letters scattered across a long name are a
            // near-worthless signal, and a gentler curve let "notep" pull
            // "Windows Software Development Kit" over Notepad itself.
            const qsizetype gap = previous < 0 ? 0 : at - previous - 1;
            penalty += 6 + 2 * int(gap);
        }
        previous = at;
        ++at;
    }
    return penalty;
}

// Tiers, best first, all on already-lowercased text. The gaps between them
// are wide enough that a better kind of match wins on the name alone;
// frecency is added afterwards and can only re-rank within about two tiers.
int matchScore(const QString &query, const QString &lowerName, const QString &initials,
               const QString &lowerAppId)
{
    if (lowerName == query)
        return 1000;
    if (lowerName.startsWith(query))
        return 900 - int(std::min<qsizetype>(80, lowerName.size() - query.size()));
    if (!initials.isEmpty()) {
        if (initials == query)
            return 880;
        if (initials.startsWith(query))
            return 820;
    }
    // A later word starting with the query: "code" finding "Visual Studio Code".
    for (qsizetype i = 1; i < lowerName.size(); ++i) {
        if (!lowerName.at(i - 1).isLetterOrNumber() && lowerName.at(i).isLetterOrNumber()
            && QStringView(lowerName).sliced(i).startsWith(query)) {
            return 760 - int(std::min<qsizetype>(50, i));
        }
    }
    if (const qsizetype at = lowerName.indexOf(query); at >= 0)
        return 700 - int(std::min<qsizetype>(60, at));
    // A run of characters in the app id outranks scattered ones in the name:
    // localised machines depend on it, where "notep" or "calc" appears only
    // in the id and the name is "Notatnik" or "Kalkulator".
    if (const qsizetype at = lowerAppId.indexOf(query); at >= 0)
        return 640 - int(std::min<qsizetype>(60, at));
    if (const int penalty = subsequencePenalty(lowerName, query); penalty >= 0)
        return 560 - std::min(120, penalty);
    // No subsequence tier on the app id. It duplicated what the name already
    // covers and was where the junk came from: nearly every packaged id ends
    // in "!App", so a query of p's and a's matched half the Store.
    return -1;
}

