AppsApi::AppsApi(QObject *parent)
    : QObject(parent)
{
    // Defensive, as in AudioApi: QApplication has already put this thread in
    // an STA. S_FALSE means we took a refcount the destructor must give back;
    // RPC_E_CHANGED_MODE means a different model is set but the apartment is
    // still usable and we hold nothing.
    const HRESULT coHr = CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED);
    m_comOwnedByUs = (coHr == S_OK || coHr == S_FALSE);
    if (FAILED(coHr) && coHr != RPC_E_CHANGED_MODE) {
        // Not fatal on its own: the scan reports its own failure and leaves
        // available false, which is what the plugin reacts to.
        qWarning().noquote() << "Apps: CoInitializeEx failed, the app list will be empty";
    }

    // Deliberately NOT under the plugins directory: the manager watches that
    // tree, so a file rewritten on every launch would hot-reload the plugin
    // out from under the user each time they used it.
    m_usagePath = QStandardPaths::writableLocation(QStandardPaths::AppDataLocation)
                  + QStringLiteral("/apps-usage.json");
    loadUsage();

    // One icon per tick, slow enough to stay out of the way of anything the
    // user is actually looking at. See the comment where it is started.
    m_iconWarmTimer.setInterval(25);
    connect(&m_iconWarmTimer, &QTimer::timeout, this, &AppsApi::warmNextIcon);

    // No scan here. Enumerating costs a few hundred ms and the plugin may not
    // even be enabled; the first refresh() from QML pays for it instead.
}

AppsApi::~AppsApi()
{
    if (m_comOwnedByUs)
        CoUninitialize();
}

void AppsApi::setIncludeDesktop(bool on)
{
    if (m_includeDesktop == on)
        return;
    m_includeDesktop = on;
    if (m_sinceScan.isValid())
        refresh(true);
}

void AppsApi::refresh(bool force)
{
    if (!force && m_sinceScan.isValid() && m_sinceScan.elapsed() < kRescanWindowMs)
        return;
    scan();
}

void AppsApi::scan()
{
    QElapsedTimer took;
    took.start();

    m_entries.clear();
    m_available = false;

    // Lowercased display names already taken, so a desktop shortcut to an
    // app the Start list already carries does not show up twice.
    QHash<QString, int> seenNames;
    scanAppsFolder(seenNames);
    const int fromShell = int(m_entries.size());
    if (m_includeDesktop)
        scanDesktop(seenNames);

    // Timed because this is the one call long enough to be felt, and split
    // because "my desktop shortcut is missing" is answered by the second
    // number: shortcuts naming an app the shell already lists are dropped.
    qInfo().noquote() << "Apps: scanned" << fromShell << "entries +"
                      << int(m_entries.size()) - fromShell << "desktop in"
                      << took.elapsed() << "ms";

    m_sinceScan.restart();
    emit changed();

    // Resolving an icon measures ~12 ms, so the eight rows of a fresh query
    // would cost about 100 ms of dead keyboard - and again on the next
    // keystroke. Warming the whole list one icon per tick instead keeps every
    // keystroke free, at the price of a couple of idle seconds after a scan
    // that the user is not waiting on. iconFor() caches, so this only ever
    // pays once per entry.
    m_warmIndex = 0;
    m_iconWarmTimer.start();
}

void AppsApi::warmNextIcon()
{
    if (m_warmIndex >= m_entries.size()) {
        m_iconWarmTimer.stop();
        return;
    }
    iconFor(m_entries.at(m_warmIndex++).id);
}

void AppsApi::scanAppsFolder(QHash<QString, int> &seenNames)
{
    IShellItem *folder = nullptr;
    HRESULT hr = SHCreateItemFromParsingName(L"shell:AppsFolder", nullptr,
                                             IID_PPV_ARGS(&folder));
    if (FAILED(hr) || !folder) {
        qWarning().noquote() << "Apps: cannot open shell:AppsFolder, Apps.available = false";
        return;
    }

    IEnumShellItems *items = nullptr;
    hr = folder->BindToHandler(nullptr, BHID_EnumItems, IID_PPV_ARGS(&items));
    folder->Release();
    if (FAILED(hr) || !items) {
        qWarning().noquote() << "Apps: cannot enumerate shell:AppsFolder, Apps.available = false";
        return;
    }

    IShellItem *item = nullptr;
    while (items->Next(1, &item, nullptr) == S_OK) {
        LPWSTR display = nullptr;
        LPWSTR parsing = nullptr;
        // PARENTRELATIVEPARSING is the app id. Two shapes turn up:
        // "<PackageFamilyName>!App" for a packaged app, and for a Win32 one
        // either a bare "chrome.exe" or a known-folder-relative path ending
        // in the exe. Prefixed it parses back in every case (verified across
        // the whole list), so the whole string is the id and only its last
        // segment is worth showing or matching.
        if (SUCCEEDED(item->GetDisplayName(SIGDN_NORMALDISPLAY, &display))
            && SUCCEEDED(item->GetDisplayName(SIGDN_PARENTRELATIVEPARSING, &parsing))) {
            const QString name = QString::fromWCharArray(display);
            const QString appId = QString::fromWCharArray(parsing);
            if (!name.isEmpty() && !appId.isEmpty()) {
                const QString leaf = appId.section(QLatin1Char('\\'), -1);
                Entry entry;
                entry.name = name;
                entry.id = kAppsFolderPrefix + appId;
                entry.subtitle = prettyAppId(leaf);
                entry.kind = leaf.contains(QLatin1Char('!')) ? QStringLiteral("store")
                                                             : QStringLiteral("app");
                entry.lowerName = name.toLower();
                // The shortened form, same as the subtitle: the package
                // family hash and the "!App" entry point are shared by nearly
                // every packaged app, so matching them invents hits rather
                // than finding any. Empty for a synthesised id, likewise.
                entry.lowerAppId = entry.subtitle.toLower();
                entry.initials = initialsOf(name);
                seenNames.insert(entry.lowerName, 1);
                m_entries.append(entry);
            }
        }
        CoTaskMemFree(display);
        CoTaskMemFree(parsing);
        item->Release();
        item = nullptr;
    }
    items->Release();
    m_available = true;
}

void AppsApi::scanDesktop(QHash<QString, int> &seenNames)
{
    QStringList dirs{ QStandardPaths::writableLocation(QStandardPaths::DesktopLocation) };
    const QString publicDir = qEnvironmentVariable("PUBLIC");
    if (!publicDir.isEmpty())
        dirs << publicDir + QStringLiteral("/Desktop");

    for (const QString &path : std::as_const(dirs)) {
        QDir dir(path);
        if (path.isEmpty() || !dir.exists())
            continue;
        const QFileInfoList files =
            dir.entryInfoList({ QStringLiteral("*.lnk"), QStringLiteral("*.url") }, QDir::Files);
        for (const QFileInfo &file : files) {
            Entry entry;
            entry.name = file.completeBaseName();
            entry.lowerName = entry.name.toLower();
            if (entry.name.isEmpty() || seenNames.contains(entry.lowerName))
                continue;
            // A plain path parses into a PIDL too, so these launch and draw
            // their icon through the same calls as an AppsFolder entry.
            entry.id = QDir::toNativeSeparators(file.absoluteFilePath());
            entry.subtitle = QStringLiteral("Desktop");
            entry.lowerAppId = QStringLiteral("desktop");
            entry.kind = QStringLiteral("shortcut");
            entry.initials = initialsOf(entry.name);
            seenNames.insert(entry.lowerName, 1);
            m_entries.append(entry);
        }
    }
}

int AppsApi::frecencyBonus(const QString &id) const
{
    const auto it = m_usage.constFind(id);
    if (it == m_usage.constEnd() || it->count <= 0)
        return 0;

    // Logarithmic on purpose: the difference between the 1st and 5th launch
    // should matter, between the 40th and 50th should not.
    const double base = std::min(160.0, 40.0 * std::log2(1.0 + it->count));
    const double days = double(QDateTime::currentMSecsSinceEpoch() - it->lastUsedMs)
                        / (24.0 * 60.0 * 60.0 * 1000.0);
    double recency = 0.15;
    if (days < 1.0)
        recency = 1.0;
    else if (days < 7.0)
        recency = 0.7;
    else if (days < 30.0)
        recency = 0.4;
    return int(base * recency);
}

QVariantList AppsApi::search(const QString &query, int limit) const
{
    const QString needle = query.trimmed().toLower();
    QList<std::pair<int, int>> ranked; // score, index into m_entries
    ranked.reserve(m_entries.size());

    for (int i = 0; i < m_entries.size(); ++i) {
        const Entry &entry = m_entries.at(i);
        int score = 0;
        if (needle.isEmpty()) {
            // Nothing typed yet: the launch history is the whole ranking, so
            // an app never launched has nothing to say and stays out.
            score = frecencyBonus(entry.id);
            if (score <= 0)
                continue;
        } else {
            score = matchScore(needle, entry.lowerName, entry.initials, entry.lowerAppId);
            if (score < 0)
                continue;
            score += frecencyBonus(entry.id);
        }
        ranked.append({ score, i });
    }

    // Name breaks ties, so the order of equally good matches does not shift
    // between scans.
    std::sort(ranked.begin(), ranked.end(), [this](const auto &a, const auto &b) {
        if (a.first != b.first)
            return a.first > b.first;
        return m_entries.at(a.second).lowerName < m_entries.at(b.second).lowerName;
    });

    QVariantList out;
    const int wanted = limit > 0 ? std::min(limit, int(ranked.size())) : int(ranked.size());
    out.reserve(wanted);
    for (int i = 0; i < wanted; ++i) {
        const Entry &entry = m_entries.at(ranked.at(i).second);
        out.append(QVariantMap{
            { QStringLiteral("id"), entry.id },
            { QStringLiteral("name"), entry.name },
            { QStringLiteral("subtitle"), entry.subtitle },
            { QStringLiteral("kind"), entry.kind },
        });
    }
    return out;
}

bool AppsApi::launch(const QString &id)
{
    if (id.isEmpty())
        return false;

    const std::wstring parsing = id.toStdWString();
    PIDLIST_ABSOLUTE pidl = nullptr;
    if (FAILED(SHParseDisplayName(parsing.c_str(), nullptr, &pidl, 0, nullptr)) || !pidl) {
        qWarning().noquote() << "Apps: cannot resolve" << id
                             << "- uninstalled since the last scan?";
        return false;
    }

    // SEE_MASK_INVOKEIDLIST runs the item's default verb through its context
    // menu, which is the one call that starts a packaged app, a Win32
    // program and a .lnk without knowing which it is holding.
    SHELLEXECUTEINFOW info = {};
    info.cbSize = sizeof(info);
    info.fMask = SEE_MASK_INVOKEIDLIST | SEE_MASK_FLAG_NO_UI;
    info.lpIDList = pidl;
    info.nShow = SW_SHOWNORMAL;
    const bool started = ShellExecuteExW(&info);
    CoTaskMemFree(pidl);

    if (!started) {
        qWarning().noquote() << "Apps: ShellExecuteEx failed for" << id;
        return false;
    }

    Usage &usage = m_usage[id];
    usage.count += 1;
    usage.lastUsedMs = QDateTime::currentMSecsSinceEpoch();
    saveUsage();
    return true;
}

bool AppsApi::runCommand(const QString &command)
{
    const QString trimmed = command.trimmed();
    if (trimmed.isEmpty())
        return false;

    // Split target from arguments the way the Run box does, honouring one
    // leading quoted path.
    QString target = trimmed;
    QString arguments;
    if (trimmed.startsWith(QLatin1Char('"'))) {
        const qsizetype end = trimmed.indexOf(QLatin1Char('"'), 1);
        if (end > 0) {
            target = trimmed.mid(1, end - 1);
            arguments = trimmed.mid(end + 1).trimmed();
        }
    } else if (const qsizetype space = trimmed.indexOf(QLatin1Char(' ')); space > 0) {
        target = trimmed.left(space);
        arguments = trimmed.mid(space + 1).trimmed();
    }

    // ShellExecute resolves a bare name against PATH and the App Paths
    // registry key, which is why "wt" or "notepad" needs no directory.
    const std::wstring wideTarget = target.toStdWString();
    const std::wstring wideArguments = arguments.toStdWString();
    const HINSTANCE result = ShellExecuteW(nullptr, L"open", wideTarget.c_str(),
                                           arguments.isEmpty() ? nullptr : wideArguments.c_str(),
                                           nullptr, SW_SHOWNORMAL);
    if (reinterpret_cast<INT_PTR>(result) <= 32) {
        qWarning().noquote() << "Apps: cannot run" << trimmed;
        return false;
    }
    return true;
}

QString AppsApi::iconFor(const QString &id)
{
    if (id.isEmpty())
        return {};
    if (const auto it = m_iconCache.constFind(id); it != m_iconCache.constEnd())
        return it.value();

    QString dataUrl;
    const std::wstring parsing = id.toStdWString();
    IShellItem *item = nullptr;
    if (SUCCEEDED(SHCreateItemFromParsingName(parsing.c_str(), nullptr, IID_PPV_ARGS(&item)))
        && item) {
        IShellItemImageFactory *factory = nullptr;
        if (SUCCEEDED(item->QueryInterface(IID_PPV_ARGS(&factory))) && factory) {
            HBITMAP bitmap = nullptr;
            const SIZE wanted = { kIconPixels, kIconPixels };
            // ICONONLY keeps this on the icon path instead of the thumbnail
            // extractors, which can hit the disk; BIGGERSIZEOK takes the next
            // size up rather than upscaling a smaller one.
            if (SUCCEEDED(factory->GetImage(wanted, SIIGBF_ICONONLY | SIIGBF_BIGGERSIZEOK,
                                            &bitmap))
                && bitmap) {
                QImage image = imageFromHBitmap(bitmap);
                DeleteObject(bitmap);
                if (!image.isNull()) {
                    if (image.width() > kIconMaxPixels || image.height() > kIconMaxPixels) {
                        image = image.scaled(kIconMaxPixels, kIconMaxPixels,
                                             Qt::KeepAspectRatio, Qt::SmoothTransformation);
                    }
                    QByteArray png;
                    QBuffer buffer(&png);
                    buffer.open(QIODevice::WriteOnly);
                    image.save(&buffer, "PNG");
                    dataUrl = QStringLiteral("data:image/png;base64,")
                              + QString::fromLatin1(png.toBase64());
                }
            }
            factory->Release();
        }
        item->Release();
    }

    if (m_iconCache.size() >= kIconCacheCap)
        m_iconCache.clear(); // simplest bound: reset rather than grow forever
    m_iconCache.insert(id, dataUrl);
    return dataUrl;
}

void AppsApi::loadUsage()
{
    QFile file(m_usagePath);
    if (!file.open(QIODevice::ReadOnly))
        return; // no history yet is the normal first run

    const QJsonObject root = QJsonDocument::fromJson(file.readAll()).object();
    for (auto it = root.constBegin(); it != root.constEnd(); ++it) {
        const QJsonObject record = it.value().toObject();
        Usage usage;
        usage.count = record.value(QStringLiteral("count")).toInt();
        // toDouble, not toInt: an epoch in milliseconds overflows 32 bits.
        usage.lastUsedMs = qint64(record.value(QStringLiteral("last")).toDouble());
        if (usage.count > 0)
            m_usage.insert(it.key(), usage);
    }
}

void AppsApi::saveUsage() const
{
    // Bounded by dropping the least recently used, so a machine that has
    // launched thousands of things over years does not carry them all.
    QList<QString> ids = m_usage.keys();
    if (ids.size() > kUsageCap) {
        std::partial_sort(ids.begin(), ids.begin() + kUsageCap, ids.end(),
                          [this](const QString &a, const QString &b) {
                              return m_usage.value(a).lastUsedMs > m_usage.value(b).lastUsedMs;
                          });
        ids.resize(kUsageCap);
    }

    QJsonObject root;
    for (const QString &id : std::as_const(ids)) {
        const Usage usage = m_usage.value(id);
        root.insert(id, QJsonObject{
                            { QStringLiteral("count"), usage.count },
                            { QStringLiteral("last"), double(usage.lastUsedMs) },
                        });
    }

    QDir().mkpath(QFileInfo(m_usagePath).absolutePath());
    QFile file(m_usagePath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        qWarning().noquote() << "Apps: cannot write" << m_usagePath
                             << "- ranking will not persist";
        return;
    }
    file.write(QJsonDocument(root).toJson(QJsonDocument::Compact));
}
